#!/usr/bin/env python3
"""Build ksu_rc_blob.h from a ROM's init.rc.

Why this exists
---------------
KernelSU normally starts its boot stages by appending a few lines to the
init.rc stream while init reads it (kernel-side read hook). Android 17's
init sizes its buffer from fstat() and reads the whole file with a single
read_iter(): there is no EOF read and no spare room in the destination
buffer, so the append can never happen and `ksud post-fs-data` is never
executed.

Instead of appending, this script produces a *same-length* variant of
init.rc where comment lines are replaced by the ksud exec lines and the
length is padded back with comment lines. The kernel then serves that
blob instead of the on-disk file; init still sees exactly the size it
fstat()ed, so parsing is unaffected.

Usage:
    ./gen_init_rc_blob.py <init.rc> <output-header> [--snippet file]

The snippet defaults to the KernelSU boot-stage lines and must be small
enough to fit in the file's comment bytes.
"""

import argparse
import sys

DEFAULT_SNIPPET = b"""
on post-fs-data
    exec u:r:ksu:s0 root -- /data/adb/ksud post-fs-data

on nonencrypted
    exec u:r:ksu:s0 root -- /data/adb/ksud services

on zygote-start
    exec u:r:ksu:s0 root -- /data/adb/ksud services
"""


def build_patched(src: bytes, snippet: bytes) -> bytes:
    orig_len = len(src)
    lines = src.split(b"\n")

    need = len(snippet)
    kept = []
    for line in lines:
        # Only whole comment lines are dropped: no instruction is touched.
        if need > 0 and line.strip().startswith(b"#") and len(line) + 1 <= need + 40:
            need -= len(line) + 1
            continue
        kept.append(line)

    patched = b"\n".join(kept) + snippet
    if len(patched) > orig_len:
        raise SystemExit(
            f"init.rc has too few comment bytes to hide the snippet: "
            f"need {len(patched) - orig_len} more"
        )

    pad = orig_len - len(patched)
    if pad == 1:
        patched += b"\n"
    elif pad > 1:
        patched += b"#" * (pad - 1) + b"\n"

    if len(patched) != orig_len:
        raise SystemExit("internal error: length changed")
    return patched


def emit_header(data: bytes, snippet: bytes, out_path: str) -> None:
    def esc(b: int) -> str:
        c = chr(b)
        if c == '"':
            return '\\"'
        if c == "\\":
            return "\\\\"
        if 32 <= b < 127:
            return c
        return "\\%03o" % b  # 3-digit octal: never absorbs following chars

    lines = [
        "/* auto-generated by gen_init_rc_blob.py - do not edit */",
        "/* init.rc variant with the KernelSU boot stages spliced in */",
        "#ifndef KSU_RC_BLOB_H",
        "#define KSU_RC_BLOB_H",
        "",
        "static const unsigned char ksu_rc_blob[] =",
    ]
    row = '    "'
    for byte in data:
        row += esc(byte)
        if len(row) >= 180:
            lines.append(row + '"')
            row = '    "'
    lines.append(row + '";')
    lines.append("static const size_t ksu_rc_blob_len = sizeof(ksu_rc_blob);")
    lines += ["", "#endif", ""]

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out_path}: {len(data)} bytes, snippet {len(snippet)} bytes")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("init_rc", help="init.rc pulled from the target ROM")
    ap.add_argument("out_header", help="generated header path")
    ap.add_argument("--snippet", help="file with the rc lines to inject")
    args = ap.parse_args()

    src = open(args.init_rc, "rb").read()
    snippet = open(args.snippet, "rb").read() if args.snippet else DEFAULT_SNIPPET
    if not snippet.endswith(b"\n"):
        snippet += b"\n"

    patched = build_patched(src, snippet)
    emit_header(patched, snippet, args.out_header)


if __name__ == "__main__":
    main()
